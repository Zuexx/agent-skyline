export const LOCALES = [
  { id: "zh-TW", label: "繁中" },
  { id: "en", label: "EN" },
];

let current = "zh-TW";

export function setLocale(locale) {
  current = dict[locale] ? locale : "zh-TW";
}

export function getLocale() {
  return current;
}

/** Default locale from the browser: Chinese for any zh-*, English otherwise. */
export function browserLocale() {
  try {
    return String(navigator.language || "").toLowerCase().startsWith("zh") ? "zh-TW" : "en";
  } catch {
    return "zh-TW";
  }
}

export function t(key, vars = {}) {
  const s = dict[current]?.[key] ?? dict["zh-TW"][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Same keys in every locale (used by tests). */
export function localeKeys(locale) {
  return Object.keys(dict[locale] ?? {});
}
